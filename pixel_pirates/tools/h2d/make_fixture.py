"""Writes game/tests/fixtures/ship_sprite_cases.json from the Python twin (run after changing ship_sprite_logic.py)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ship_sprite_logic as L  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def build() -> dict:
    headings = [0.0, 10.0, 11.25, 11.26, 22.5, 45.0, 90.0, 180.0, 337.4, 348.75, 348.76, 359.9, 360.0, -22.5, 725.0]
    frames = [{"heading": h, "frame": L.heading_frame(h)} for h in headings]
    trims = []
    for h in (0.0, 45.0, 90.0, 135.0, 180.0, 225.0, 270.0, 315.0, 355.0):
        for w in (0.0, 90.0, 180.0, 270.0, 300.0):
            trims.append({"heading": h, "wind_from": w, "row": L.trim_row(h, w)})
    speeds = [{"kn": k, "scene_ms": round(L.scene_speed_ms(k), 6)} for k in (0.0, 0.6, 3.9, 5.0, 9.0)]
    waves = []
    for wm, wf, ice in ((0.0, 270.0, 0.0), (1.5, 270.0, 0.0), (3.2, 45.0, 0.0), (7.0, 200.0, 0.0), (3.0, 90.0, 0.8)):
        p = L.wave_params(wm, wf, ice)
        pts = [(0.0, 0.0, 0.0), (10.0, -5.0, 3.5), (-37.5, 80.0, 12.0), (123.4, 56.7, 99.9)]
        waves.append({"wave_m": wm, "wind_from": wf, "ice": ice,
                      "points": [{"x": x, "z": z, "t": t, "h": round(L.wave_height(p, x, z, t), 6)} for x, z, t in pts]})
    return {"_doc": "Generated by tools/h2d/make_fixture.py from ship_sprite_logic.py. Replayed by tests/test_h2d.gd.",
            "frames": frames, "trims": trims, "speeds": speeds, "waves": waves}


if __name__ == "__main__":
    out = ROOT / "game/tests/fixtures/ship_sprite_cases.json"
    out.write_text(json.dumps(build(), indent=1) + "\n")
    print("wrote", out.relative_to(ROOT))
