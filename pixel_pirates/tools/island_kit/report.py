"""Writes the A6 report: size-true contact sheet, detail previews and a markdown table (numbers come from the baked maps)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import bake as B  # noqa: E402
import island_checks as IC  # noqa: E402
import preview  # noqa: E402
import sameness as S  # noqa: E402

FX = B.ROOT / "game" / "tests" / "fixtures" / "islands"
OUT = B.ROOT / "art_bible" / "island_kit"


def main() -> int:
    ctx = B.load_context()
    recs = B.read_island_file(FX / "islands.json")
    maps = [IC.load_map(FX / "maps" / f"{r['id']}.map.json") for r in recs]
    OUT.mkdir(parents=True, exist_ok=True)
    preview.contact_sheet(maps).save(OUT / "fixture_sheet.png")
    for r, m in zip(recs, maps):
        if r["id"] in ("isl_903", "isl_907", "isl_906"):
            preview.render(m, 4).save(OUT / f"detail_{r['id']}_{r['template'].replace('tpl_', '')}.png")
    probs, warns, pairs = S.check_catalog(list(zip(recs, maps)), ctx)
    lines = ["# A6 island kit report (generated by tools/island_kit/report.py)", "",
             "Fixture islands are test data (isl_901..910), not part of the world registry. 1 tile = 2 m; walking speed "
             f"{ctx['tuning']['move.walk_speed_mps']} m/s (provisional).", "",
             "| island | template | kit | tier | grid | island size | land | POIs | landings | explore time | tier budget | props |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r, m in zip(recs, maps):
        s = m["stats"]
        n = m["size"][0]
        lines.append(f"| {r['id']} | {r['template'].replace('tpl_', '')} | {r['kits'][0].replace('kit_', '')} | {r['tier']} | {n}x{n} | {n * 2} m | {s['land_fraction'] * 100:.0f}% | {s['pois']} | {s['landings']} | "
                     f"{s['explore_minutes']:.1f} min | {B.explore_budget(ctx, r['tier']):.0f} min | {s['props']} |")
    lines += ["", "Explore time = nearest-neighbour walk from the first landing through every POI (trail-cost weighted: wading x1.6, uphill penalty), without dwell time.", "",
              "## Most similar silhouettes in the fixture set (limit " + str(ctx["tuning"]["island.sameness_max_iou"]) + ")", "", "| pair | overlap |", "|---|---|"]
    for a, b, v in pairs[:6]:
        lines.append(f"| {a} / {b} | {v:.2f} |")
    lines += ["", f"Catalog problems: {len(probs)}; warnings: {len(warns)}."]
    (B.ROOT / "docs" / "A6_ISLAND_KIT_REPORT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-14:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
