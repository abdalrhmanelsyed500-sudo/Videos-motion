"""ISLAND REGISTRY document (Canon requirement), generated from the data files (Module A7).
  python tools/data_tools/registry_doc.py          # write docs/ISLAND_REGISTRY.md
  python tools/data_tools/registry_doc.py --check  # exit 1 if the file is out of date (used by check_project.py)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools" / "island_kit"))
import validate_data as V  # noqa: E402

DOC = ROOT / "docs" / "ISLAND_REGISTRY.md"
TARGETS = {1: (12, 15), 2: (20, 25), 3: (15, 25)}


def build(data_dir: Path | None = None) -> str:
    data_dir = data_dir or V.DATA
    _, _, res = V.run(data_dir)
    isl = sorted(res["tables"].get("island", {}).values(), key=lambda r: r["id"])
    maps = {}
    for r in isl:
        p = data_dir / "islands" / "maps" / f"{r['id']}.map.json"
        if p.exists():
            maps[r["id"]] = json.loads(p.read_text())["stats"]
    tiers = {t: sum(1 for r in isl if r["tier"] == t) for t in (1, 2, 3)}
    clustered = sum(1 for r in isl if any(n["distance_km"] < 25 for n in r.get("neighbors", [])))
    L = ["# ISLAND REGISTRY (generated by tools/data_tools/registry_doc.py - do not edit by hand)", "",
         "Source of truth: `game/data/islands/*.json`. Test fixtures (isl_901..910) are not listed.", "",
         f"**{len(isl)} islands** (target 50+). Tier 1: {tiers[1]} (target {TARGETS[1][0]}-{TARGETS[1][1]}); Tier 2: {tiers[2]} "
         f"(target {TARGETS[2][0]}-{TARGETS[2][1]}); Tier 3: {tiers[3]} (target {TARGETS[3][0]}-{TARGETS[3][1]}). "
         f"In clusters (a neighbour closer than 25 km): {clustered} (must stay a minority).", ""]
    st = {}
    for r in isl:
        st[r["status"]] = st.get(r["status"], 0) + 1
    L.append("Status: " + (", ".join(f"{k} {v}" for k, v in sorted(st.items())) if st else "none yet (planned 0, designed 0, built 0, tested 0)"))
    L += ["", "| ID | name | tier | biome | region | position km | neighbours (km / sloop h) | template | kit | hook kind | explore min | status |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    if not isl:
        L.append("| (none yet; the master list comes from E3) | | | | | | | | | | | |")
    for r in isl:
        nb = "; ".join(f"{n['id']}: {n['distance_km']} / {n['sail_hours_sloop']}" for n in r.get("neighbors", [])) or "isolated"
        mins = maps.get(r["id"], {}).get("explore_minutes", "-")
        L.append(f"| {r['id']} | {r['name']} | {r['tier']} | {r['biome']} | {r['region']} | {r['position']['x_km']}, {r['position']['y_km']} | {nb} | "
                 f"{r.get('template', '-')} | {(r.get('kits') or ['-'])[0]} | {r.get('hook_kind', '-')} | {mins} | {r['status']} |")
    if isl:
        hooks: dict[str, int] = {}
        tpls: dict[str, int] = {}
        for r in isl:
            hooks[r.get("hook_kind", "-")] = hooks.get(r.get("hook_kind", "-"), 0) + 1
            tpls[r.get("template", "-")] = tpls.get(r.get("template", "-"), 0) + 1
        L += ["", "Hook kinds used: " + ", ".join(f"{k} x{v}" for k, v in sorted(hooks.items())),
              "Templates used: " + ", ".join(f"{k} x{v}" for k, v in sorted(tpls.items()))]
    return "\n".join(L) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not DOC.exists() or DOC.read_text() != text:
            print("docs/ISLAND_REGISTRY.md is out of date: run python tools/data_tools/registry_doc.py")
            return 1
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
