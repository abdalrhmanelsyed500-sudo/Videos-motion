"""Writes art_bible/LOOK_LAB_REPORT.md from stats.json (our stills) vs ref_measure.json (the two HD-2D references)."""
import json
from pathlib import Path
R = Path(__file__).resolve().parents[2] / "art_bible"
ref = json.loads((R / "ref_measure.json").read_text())
st = json.loads((R / "looklab_stills" / "stats.json").read_text())


def refstats(r):
    v = r["vignette_lum_by_radius"]
    b = r["sharp_by_band_top_to_branch"] if False else r["sharp_by_band_top_to_bottom"]
    return {"mean_sat": r["mean_sat"], "lum_p1": r["lum_pcts"]["1"], "lum_p50": r["lum_pcts"]["50"],
            "edge_over_centre_lum": round(v[9] / v[0], 3), "sharp_edge_over_peak": round((b[0] + b[-1]) / 2 / max(b), 3),
            "sharp_peak_band": b.index(max(b)), "RB_shadow": r["RB_ratio_shadow"]}


rows = [("REF A (town square)", refstats(ref["A"])), ("REF B (forest camp)", refstats(ref["B"]))] + list(st.items())
cols = ["mean_sat", "lum_p1", "lum_p50", "edge_over_centre_lum", "sharp_edge_over_peak", "sharp_peak_band", "RB_shadow"]
L = ["# LOOK LAB REPORT (generated by tools/looklab/make_report.py)", "",
     "Global image statistics of our Look Lab stills versus the two reference images. Same formulas for both",
     "(see `tools/looklab/looklab.py::stats`, references measured by the A3 analysis script, results in `ref_measure.json`).", "",
     "| image | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
for n, s in rows:
    L.append(f"| {n} | " + " | ".join(str(s[c]) for c in cols) + " |")
L += ["", "Reading guide: `mean_sat` colour richness; `lum_p1` how dark the darkest 1% is; `lum_p50` median brightness;",
      "`edge_over_centre_lum` vignette (lower = stronger); `sharp_edge_over_peak` tilt-shift (lower = stronger blur at the top/bottom);",
      "`sharp_peak_band` which tenth of the screen height is sharpest (0 = top; both refs peak at 5); `RB_shadow` warmth of the darkest 20%.", "",
      "## Honest reading", "",
      "* Matches: colour richness (0.44-0.64 target, golden beach 0.63), median brightness (refs 0.23-0.26, ours 0.34 = slightly bright),",
      "  vignette (refs 0.13-0.33, ours 0.34 standard), tilt-shift strength (ref B 0.016 / ref A 0.30; ours 0.008 = at or beyond the strong end, so mild moods use `tilt_strength` < 1).",
      "* Near miss: sharpest band. Both refs peak in band 5 (50-60% of screen height), ours in band 4 (40-50%): content-dependent (our scene has its most detailed",
      "  objects slightly higher) while the design value `focus_y` = 0.55 sits in band 5. Re-check with real art.",
      "* Misses: our darkest 1% is lighter (0.11 vs 0.02-0.05, because of the plum shadow lift and heavy blur), and the golden-hour shadows are less warm",
      "  (R/B 2.4 vs 3.5-6 in the refs). Tuning knobs: `grade.shadow_lift`, mood `ambient` colour. Left as-is until the real art exists: tuning global",
      "  numbers on placeholder content would over-fit.",
      "* The reference images are low-res screenshots (588x330 and 554x554) and their own compression noise inflates their `lum_p1` and `RB_shadow`;",
      "  treat these as ranges, not exact targets.",
      "* What this does NOT prove: final art quality. Placeholder sprites are mannequins; ground tiles are plain next to the refs' dense hand-drawn detail,",
      "  and the Look Lab approximates the shader (Gaussian levels, not the 12-tap golden-angle blur)."]
(R / "LOOK_LAB_REPORT.md").write_text("\n".join(L) + "\n")
print("\n".join(L[:14]))
